@dataclass
class CritiqueItem:
    """A specific issue or constructive comment raised by a reviewer."""
    severity: str  # 'CRITICAL', 'MAJOR', 'MINOR', 'PRAISE'
    category: str  # 'identification', 'citation', 'logic', 'framing', 'boundary', 'style'
    sentence_anchor: str  # The specific text passage or section triggering the comment
    critique: str  # Detailed referee explanation
    suggested_remedy: str  # Actionable advice on how to address the issue
    resolved_in_revision: bool = False

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class ReviewerReport:
    """Evaluation report generated by one of the 5 reviewer panel seats."""
    seat_id: str  # 'eic', 'methodology', 'domain', 'perspective', 'devils_advocate'
    seat_name: str  # Human-readable seat title
    score: float  # 1.0 to 10.0 scale
    strengths: list[str] = field(default_factory=list)
    critiques: list[CritiqueItem] = field(default_factory=list)
    summary_verdict: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "seat_id": self.seat_id,
            "seat_name": self.seat_name,
            "score": round(self.score, 1),
            "strengths": self.strengths,
            "critiques": [c.to_dict() for c in self.critiques],
            "summary_verdict": self.summary_verdict,
        }


@dataclass
class RoadmapItem:
    """A prioritized task in the editorial revision roadmap."""
    priority: str  # 'MUST-ADDRESS', 'RECOMMENDED', 'POLISH'
    source_seats: list[str]
    issue: str
    action_required: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class AdjudicationDecision:
    """The synthesized editorial decision and arbitration across all 5 seats."""
    composite_score: float  # 1.0 - 10.0
    editorial_decision: str  # 'ACCEPT', 'MINOR_REVISION', 'MAJOR_REVISION', 'REJECT_AND_RESUBMIT'
    target_venue_tier: str  # 'top', 'field_top', 'general', 'working_paper'
    reviewer_reports: list[ReviewerReport] = field(default_factory=list)
    consensus_strengths: list[str] = field(default_factory=list)
    consensus_weaknesses: list[str] = field(default_factory=list)
    arbitrated_disagreements: list[str] = field(default_factory=list)
    da_critical_count: int = 0
    revision_roadmap: list[RoadmapItem] = field(default_factory=list)
    editorial_letter: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "composite_score": round(self.composite_score, 2),
            "editorial_decision": self.editorial_decision,
            "target_venue_tier": self.target_venue_tier,
            "reviewer_reports": [r.to_dict() for r in self.reviewer_reports],
            "consensus_strengths": self.consensus_strengths,
            "consensus_weaknesses": self.consensus_weaknesses,
            "arbitrated_disagreements": self.arbitrated_disagreements,
            "da_critical_count": self.da_critical_count,
            "revision_roadmap": [item.to_dict() for item in self.revision_roadmap],
            "editorial_letter": self.editorial_letter,
        }


@dataclass
class DualAgentPackage:
    """Complete output package containing first-round review, revised draft, and response letter."""
    initial_adjudication: AdjudicationDecision
    revised_text: Optional[str] = None
    response_to_reviewers: Optional[str] = None
    post_revision_adjudication: Optional[AdjudicationDecision] = None
    score_delta: float = 0.0

    @property
    def has_revision(self) -> bool:
        return self.revised_text is not None

    def to_dict(self) -> dict[str, Any]:
        return {
            "initial_adjudication": self.initial_adjudication.to_dict(),
            "has_revision": self.has_revision,
            "score_delta": round(self.score_delta, 2),
            "revised_text": self.revised_text,
            "response_to_reviewers": self.response_to_reviewers,
            "post_revision_adjudication": self.post_revision_adjudication.to_dict() if self.post_revision_adjudication else None,
        }



