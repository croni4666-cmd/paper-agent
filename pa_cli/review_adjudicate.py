"""pa_cli.review_adjudicate — Dual-agent review & adjudication loop.

Per ROADMAP [P3-33]:
  Connects the 5-role academic reviewer panel with Paper Agent's M2/M5 adjudication schema,
  evaluating drafted literature review sections against strict peer-review criteria:
  (1) Journal-Fit Reviewer (scope, academic framing, structural balance, research gap)
  (2) Methodology & Identification Reviewer (causal identification rigor, overclaim detection)
  (3) Domain Literature Reviewer (citation coverage, seminal balance, citation density)
  (4) Boundary Conditions Reviewer (generalizability, institutional qualifiers, moderators)
  (5) Devil's Advocate Reviewer (logic fallacies, cherry-picking, confirmation bias, counter-arguments)
  (6) Editorial Adjudication & Prioritized Revision Roadmap (Accept / Minor / Major / Reject)
  (7) Drafter Revision Loop (--revise): Automated draft refinement and "Response to Reviewers" letter.

Global Rule audit:
  100% offline-first execution; pure Python heuristic NLP analysis;
  zero cloud dependencies; zero external API cost; Windows safe ASCII fallback.
"""
from __future__ import annotations

import json
