def format_adjudication_table(pkg: DualAgentPackage) -> str:
    """Format review and adjudication result as high-density ASCII table."""
    adj = pkg.initial_adjudication
    lines: list[str] = [
        "=" * 86,
        " DUAL-AGENT PEER REVIEW & ADJUDICATION REPORT [P3-33]",
        "=" * 86,
        f" Target Journal Tier: {adj.target_venue_tier.upper()}",
        f" Editorial Verdict:   {adj.editorial_decision}",
        f" Composite Score:     {adj.composite_score:.2f} / 10.0",
        f" DA Critical Alerts:  {adj.da_critical_count}",
        "-" * 86,
        " REFEREE PANEL BREAKDOWN (5 SEATS):",
        f"  1. Journal-Fit Reviewer:          {adj.reviewer_reports[0].score:4.1f}/10.0  [{adj.reviewer_reports[0].summary_verdict}]",
        f"  2. Methodology & Identification:  {adj.reviewer_reports[1].score:4.1f}/10.0  [{adj.reviewer_reports[1].summary_verdict}]",
        f"  3. Domain Literature Reviewer:    {adj.reviewer_reports[2].score:4.1f}/10.0  [{adj.reviewer_reports[2].summary_verdict}]",
        f"  4. Boundary Conditions Reviewer:  {adj.reviewer_reports[3].score:4.1f}/10.0  [{adj.reviewer_reports[3].summary_verdict}]",
        f"  5. Devil's Advocate Reviewer:     {adj.reviewer_reports[4].score:4.1f}/10.0  [{adj.reviewer_reports[4].summary_verdict}]",
        "-" * 86,
        " PRIORITIZED REVISION ROADMAP:",
    ]
    if not adj.revision_roadmap:
        lines.append("  (No critical or major revisions required)")
    else:
        for idx, item in enumerate(adj.revision_roadmap[:5], 1):
            lines.append(f"  {idx}. [{item.priority}] {item.issue[:65]}...")
            lines.append(f"     Action: {item.action_required[:70]}...")

    if pkg.has_revision and pkg.post_revision_adjudication:
        post = pkg.post_revision_adjudication
        lines.extend([
            "-" * 86,
            " DUAL-AGENT REVISION LOOP RESULTS (--revise):",
            f"  Pre-Revision Decision:  {adj.editorial_decision} ({adj.composite_score:.2f})",
            f"  Post-Revision Decision: {post.editorial_decision} ({post.composite_score:.2f})",
            f"  Score Improvement Delta: +{pkg.score_delta:.2f} points",
            f"  Status: {'UPGRADED & RESOLVED' if post.composite_score > adj.composite_score else 'STABLE'}",
        ])

    lines.append("=" * 86)
    return "\n".join(lines)


def format_adjudication_markdown(pkg: DualAgentPackage) -> str:
    """Format full adjudication package as clean academic Markdown."""
    adj = pkg.initial_adjudication
    lines: list[str] = [
        "# Academic Literature Review Peer Review & Adjudication Package\n",
        f"- **Target Venue Tier**: `{adj.target_venue_tier}`",
        f"- **Editorial Decision**: **{adj.editorial_decision}**",
        f"- **Composite Quality Score**: `{adj.composite_score:.2f} / 10.0`",
        f"- **Devil's Advocate Critical Alerts**: `{adj.da_critical_count}`\n",
        "## 1. Editorial Decision Letter\n",
        adj.editorial_letter,
        "\n## 2. Detailed Referee Reports (5-Seat Panel)\n",
    ]

    for r in adj.reviewer_reports:
        lines.append(f"### {r.seat_name} (Score: {r.score:.1f}/10.0)\n")
        lines.append(f"*{r.summary_verdict}*\n")
        if r.strengths:
            lines.append("**Strengths**:")
            for s in r.strengths:
                lines.append(f"- {s}")
            lines.append("")
        if r.critiques:
            lines.append("**Critiques & Required Amendments**:")
            for c in r.critiques:
                lines.append(f"- `[{c.severity}]` *{c.sentence_anchor}*: {c.critique}")
                lines.append(f"  - *Remedy*: {c.suggested_remedy}")
            lines.append("")

    lines.append("## 3. Prioritized Revision Roadmap\n")
    for idx, item in enumerate(adj.revision_roadmap, 1):
        lines.append(f"{idx}. `[{item.priority}]` from *{', '.join(item.source_seats)}*")
        lines.append(f"   - **Issue**: {item.issue}")
        lines.append(f"   - **Action Required**: {item.action_required}\n")

    if pkg.has_revision and pkg.post_revision_adjudication:
        post = pkg.post_revision_adjudication
        lines.extend([
            "## 4. Dual-Agent Revision Outcome & Verification\n",
            f"- **Pre-Revision Score**: `{adj.composite_score:.2f}` ({adj.editorial_decision})",
            f"- **Post-Revision Score**: `{post.composite_score:.2f}` (**{post.editorial_decision}**)",
            f"- **Score Improvement Delta**: `+{pkg.score_delta:.2f}` points\n",
            "### Point-by-Point Author Response Letter\n",
            pkg.response_to_reviewers or "",
            "\n### Revised Literature Review Text\n",
            "```markdown",
            pkg.revised_text or "",
            "```\n",
        ])

    lines.append("---\n*Generated by Paper Agent Review & Adjudication System (`pa review-adjudicate`).*\n")
    return "\n".join(lines)


def format_adjudication_json(pkg: DualAgentPackage) -> str:
    """Format as complete JSON provenance package."""
    return json.dumps(pkg.to_dict(), indent=2, ensure_ascii=False)
