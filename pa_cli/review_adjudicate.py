def split_sentences(text: str) -> list[str]:
    """Split text into sentences while protecting citations and academic abbreviations."""
    protected = text
    subs = {
        "e.g.": "__EG__",
        "i.e.": "__IE__",
        "et al.": "__ETAL__",
        "vs.": "__VS__",
        "cf.": "__CF__",
        "p.": "__PG__",
        "pp.": "__PPG__",
        "vol.": "__VOL__",
        "no.": "__NUM__",
    }
    for k, v in subs.items():
        protected = re.sub(re.escape(k), v, protected, flags=re.IGNORECASE)

    raw_sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"'\[@])", protected)
    sentences = []
    for s in raw_sentences:
        clean = s.strip()
        for k, v in subs.items():
            clean = clean.replace(v, k)
        if len(clean) > 5:
            sentences.append(clean)
    return sentences


def count_citations(text: str) -> int:
    """Count explicit academic citations in text."""
    citeproc = len(re.findall(r"\[@[^\]]+\]", text))
    latex = len(re.findall(r"\\(?:cite|citep|citet|autocite)\{[^\}]+\}", text))
    inline_yr = len(re.findall(r"\b[A-Z][a-zA-Z\s]{1,25}\s*(?:et\s*al\.\s*)?\((?:19|20)\d{2}\)", text))
    return citeproc + latex + inline_yr


def extract_paragraphs(text: str) -> list[str]:
    """Extract non-empty paragraphs from markdown text."""
    paras = [p.strip() for p in text.split("\n\n") if p.strip()]
    return [p for p in paras if not p.startswith("#")]


# Causal overclaim verb pattern: unhedged strong assertion without identification qualifier
CAUSAL_OVERCLAIM_PAT = re.compile(
    r"\b(?:proves?\s+that|definitively\s+(?:shows?|demonstrates?)|unquestionably\s+causes?|directly\s+establishes\s+causality|guarantees?\s+that)\b",
    re.IGNORECASE,
)

# Identification strategy keywords indicating methodological rigor
IDENTIFICATION_PAT = re.compile(
    r"\b(?:difference[- ]in[- ]differences|DID|two[- ]way\s+fixed\s+effects|TWFE|instrumental\s+variable|IV|2SLS|regression\s+discontinuity|RDD|synthetic\s+control|exogenous\s+shock|natural\s+experiment|parallel\s+trends?|exclusion\s+restriction)\b",
    re.IGNORECASE,
)

# Boundary condition and heterogeneity keywords
BOUNDARY_PAT = re.compile(
    r"\b(?:heterogeneity|boundary\s+condition|cross[- ]sectional\s+variation|moderating\s+effect|conditional\s+on|subsample|SOE[s]?|non[- ]SOE[s]?|firm\s+size|institutional\s+context|emerging\s+markets?|financial\s+constraints?)\b",
    re.IGNORECASE,
)

# Counter-argument and empirical tension keywords
TENSION_PAT = re.compile(
    r"\b(?:however|in\s+contrast|contrary\s+to|conversely|divergent\s+findings|mixed\s+evidence|competing\s+hypotheses|unresolved\s+debate|conflicting\s+results)\b",
    re.IGNORECASE,
)


