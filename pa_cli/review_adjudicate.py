def review_journal_fit(text: str, venue_tier: str = "field_top") -> ReviewerReport:
    """Seat 1: Journal-Fit Reviewer. Evaluates scope, framing, and research gap."""
    critiques: list[CritiqueItem] = []
    strengths: list[str] = []
    base_score = 8.5

    # 1. Structure check: Does it have thematic sections or just a wall of text?
    headers = re.findall(r"^#{1,4}\s+(.+)$", text, re.MULTILINE)
    if len(headers) >= 3:
        strengths.append(f"Well-structured thematic presentation across {len(headers)} subsections.")
    else:
        base_score -= 1.5
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="framing",
            sentence_anchor="Manuscript structural layout",
            critique="The literature review lacks clear thematic subsections (e.g., Theoretical Foundations, Core Empirical Debates, Gaps). It reads like an unstructured sequence of summaries.",
            suggested_remedy="Divide the review into structured thematic sections: Theoretical Foundations, Empirical Identification, and Research Gaps.",
        ))

    # 2. Research gap check: Does it articulate what remains unsolved?
    has_gap = bool(re.search(r"\b(?:research\s+gap|unresolved|remains\s+unclear|open\s+question|unaddressed|future\s+inquiry)\b", text, re.I))
    if has_gap:
        strengths.append("Clearly demarcates existing empirical literature from unaddressed research gaps.")
    else:
        base_score -= 1.2
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="framing",
            sentence_anchor="Concluding paragraphs",
            critique="The review fails to explicitly articulate an unresolved research gap. A high-tier journal requires authors to explain what literature has NOT established.",
            suggested_remedy="Conclude the review with an explicit 'Unresolved Tensions & Research Gaps' subsection motivating the study's incremental contribution.",
        ))

    # 3. Tone and formality check
    informal = re.findall(r"\b(?:obviously|everyone\s+knows|a\s+lot\s+of|lots\s+of|super\s+important|huge\s+impact)\b", text, re.I)
    if informal:
        base_score -= 0.8
        critiques.append(CritiqueItem(
            severity="MINOR",
            category="style",
            sentence_anchor=f"Informal phrase: '{informal[0]}'",
            critique=f"Colloquial terminology detected ('{informal[0]}'). Academic journals expect formal scholarly rhetoric.",
            suggested_remedy="Replace informal vernacular with objective scholarly terminology (e.g. 'substantial effect', 'widely acknowledged').",
        ))
    else:
        strengths.append("Professional scholarly tone and academic register maintained throughout.")

    # Venue tier expectations
    if venue_tier == "top" and base_score > 7.0:
        base_score -= 0.5  # Top tier journals apply stricter standards

    score = max(1.0, min(10.0, base_score))
    verdict = "Acceptable journal framing" if score >= 7.0 else "Needs clearer scholarly motivation and structure"
    return ReviewerReport(
        seat_id="eic",
        seat_name="Journal-Fit Reviewer",
        score=score,
        strengths=strengths,
        critiques=critiques,
        summary_verdict=verdict,
    )


def review_methodology(text: str) -> ReviewerReport:
    """Seat 2: Methodology & Identification Reviewer. Evaluates causal rigor and identification defense."""
    critiques: list[CritiqueItem] = []
    strengths: list[str] = []
    base_score = 8.5
    sentences = split_sentences(text)

    # 1. Causal overclaim detection
    overclaims: list[str] = []
    for s in sentences:
        if CAUSAL_OVERCLAIM_PAT.search(s):
            overclaims.append(s)

    if overclaims:
        base_score -= min(3.0, len(overclaims) * 1.5)
        for oc in overclaims[:2]:
            critiques.append(CritiqueItem(
                severity="CRITICAL",
                category="identification",
                sentence_anchor=oc[:90] + ("..." if len(oc) > 90 else ""),
                critique="Causal overclaim detected. Strong assertion of causality ('proves that', 'definitively shows') without attributing to an explicit exogenous identification strategy.",
                suggested_remedy="Hedge the causal assertion; condition claims on empirical identification strategies (e.g. 'Evidence exploiting staggered policy shocks indicates...').",
            ))
    else:
        strengths.append("Cautious empirical claims without unhedged causal overstatements.")

    # 2. Identification strategy awareness
    id_matches = IDENTIFICATION_PAT.findall(text)
    if len(id_matches) >= 2:
        strengths.append(f"Substantive engagement with causal identification methodologies ({', '.join(set(id_matches[:3]))}).")
    else:
        base_score -= 1.5
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="identification",
            sentence_anchor="Empirical review discussion",
            critique="The review discusses empirical findings in the abstract without detailing the econometric identification strategies (e.g. DID, IV, TWFE) used to resolve endogeneity.",
            suggested_remedy="Explicitly distinguish between simple correlational OLS evidence and quasi-experimental causal identification designs in cited literature.",
        ))

    score = max(1.0, min(10.0, base_score))
    verdict = "Methodological discussions are rigorous" if score >= 7.0 else "Requires rigorous identification distinction and hedging"
    return ReviewerReport(
        seat_id="methodology",
        seat_name="Methodology & Identification Reviewer",
        score=score,
        strengths=strengths,
        critiques=critiques,
        summary_verdict=verdict,
    )


def review_domain_literature(text: str) -> ReviewerReport:
    """Seat 3: Domain Literature & Citation Reviewer. Evaluates citation coverage and reference grounding."""
    critiques: list[CritiqueItem] = []
    strengths: list[str] = []
    base_score = 8.0
    paras = extract_paragraphs(text)
    total_cites = count_citations(text)

    # 1. Overall citation volume
    word_count = len(text.split())
    cite_density = (total_cites / max(1, word_count)) * 100  # citations per 100 words

    if total_cites >= 5 and cite_density >= 1.0:
        strengths.append(f"Solid bibliographic grounding with {total_cites} citations ({cite_density:.1f} per 100 words).")
    elif total_cites >= 2:
        base_score -= 1.0
        critiques.append(CritiqueItem(
            severity="MINOR",
            category="citation",
            sentence_anchor="Body text",
            critique=f"Citation density is relatively sparse ({total_cites} citations total). Several empirical claims are made without direct parenthetical citations.",
            suggested_remedy="Anchor every substantive empirical finding to verified citations (e.g. `[@author2020]`).",
        ))
    else:
        base_score -= 3.0
        critiques.append(CritiqueItem(
            severity="CRITICAL",
            category="citation",
            sentence_anchor="Body text",
            critique="Severe lack of citations. Academic literature reviews must ground claims in peer-reviewed scholarship.",
            suggested_remedy="Incorporate full BibTeX citations for each theoretical claim and empirical finding.",
        ))

    # 2. Check for naked paragraphs (paragraphs asserting empirical facts with 0 citations)
    naked_paras = [p for p in paras if count_citations(p) == 0 and len(p.split()) > 35]
    if naked_paras:
        base_score -= min(2.0, len(naked_paras) * 0.8)
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="citation",
            sentence_anchor=naked_paras[0][:80] + "...",
            critique="Found substantive paragraphs making empirical assertions without a single cited reference.",
            suggested_remedy="Add direct literature citations supporting the claims in these paragraphs.",
        ))

    score = max(1.0, min(10.0, base_score))
    verdict = "Literature grounding is satisfactory" if score >= 7.0 else "Citation coverage needs substantial reinforcement"
    return ReviewerReport(
        seat_id="domain",
        seat_name="Domain Literature Reviewer",
        score=score,
        strengths=strengths,
        critiques=critiques,
        summary_verdict=verdict,
    )


def review_boundary_conditions(text: str) -> ReviewerReport:
    """Seat 4: Boundary Conditions Reviewer. Evaluates generalizability, heterogeneity, and context."""
    critiques: list[CritiqueItem] = []
    strengths: list[str] = []
    base_score = 8.5

    # 1. Look for boundary conditions or heterogeneity discussion
    boundary_matches = BOUNDARY_PAT.findall(text)
    if len(boundary_matches) >= 2:
        strengths.append(f"Commendable sensitivity to institutional boundary conditions and heterogeneity dimensions ({', '.join(set(boundary_matches[:3]))}).")
    else:
        base_score -= 2.0
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="boundary",
            sentence_anchor="Literature synthesis",
            critique="The draft portrays effects as universally monotonic, overlooking key institutional boundary conditions (e.g. firm ownership, financial constraints, regulatory environment).",
            suggested_remedy="Incorporate a dedicated discussion of heterogeneity and moderating factors explaining where and when the effect operates.",
        ))

    # 2. Check for sample context specificity
    sample_spec = re.search(r"\b(?:sample|firm[- ]level|cross[- ]country|panel\s+data|survey|listed\s+firms?|enterprises?|firms?)\b", text, re.I)
    if sample_spec:
        strengths.append("Clearly specifies empirical sample settings and data levels of cited studies.")
    else:
        base_score -= 1.0
        critiques.append(CritiqueItem(
            severity="MINOR",
            category="boundary",
            sentence_anchor="Empirical review passages",
            critique="Omits empirical sample context (e.g. whether findings apply to S&P 500, Chinese A-shares, or European SMEs).",
            suggested_remedy="State the institutional context and sample period when discussing empirical findings.",
        ))

    score = max(1.0, min(10.0, base_score))
    verdict = "Adequately contextualized" if score >= 7.0 else "Overly generic; lacks institutional boundary qualifiers"
    return ReviewerReport(
        seat_id="perspective",
        seat_name="Boundary Conditions Reviewer",
        score=score,
        strengths=strengths,
        critiques=critiques,
        summary_verdict=verdict,
    )


def review_devils_advocate(text: str) -> ReviewerReport:
    """Seat 5: Devil's Advocate Reviewer. Identifies confirmation bias, cherry-picking, and counter-arguments."""
    critiques: list[CritiqueItem] = []
    strengths: list[str] = []
    base_score = 8.5

    # 1. Confirmation bias / One-sided literature representation
    tensions = TENSION_PAT.findall(text)
    if tensions:
        strengths.append("Acknowledges empirical debates and competing perspectives rather than one-sided cherry-picking.")
    else:
        base_score -= 2.5
        critiques.append(CritiqueItem(
            severity="CRITICAL",
            category="logic",
            sentence_anchor="Core debate synthesis",
            critique="Confirmation bias detected. The review presents a monolithic consensus without citing competing hypotheses, contradictory findings, or null results in the literature.",
            suggested_remedy="Incorporate counter-theories and dissenting studies (e.g., 'In contrast, other scholars find null or countervailing effects due to compliance burdens').",
        ))

    # 2. Non-sequitur or broad sweeping logic leaps
    sweeping = re.findall(r"\b(?:inevitably|undoubtedly|completely\s+solves?|leaves\s+no\s+doubt|eliminates\s+all)\b", text, re.I)
    if sweeping:
        base_score -= 1.8
        critiques.append(CritiqueItem(
            severity="MAJOR",
            category="logic",
            sentence_anchor=f"Sweeping assertion: '{sweeping[0]}'",
            critique=f"Logical non-sequitur or hyperbolic claim ('{sweeping[0]}'). Academic findings rarely eliminate all ambiguity.",
            suggested_remedy="Moderate claims to reflect probabilistic scientific inquiry.",
        ))
    else:
        strengths.append("Logical progressions are measured and logically defensible.")

    score = max(1.0, min(10.0, base_score))
    verdict = "No fatal logical fallacies" if score >= 7.0 else "Vulnerable to confirmation bias and counter-argument attack"
    return ReviewerReport(
        seat_id="devils_advocate",
        seat_name="Devil's Advocate Reviewer",
        score=score,
        strengths=strengths,
        critiques=critiques,
        summary_verdict=verdict,
    )


# ==============================================================================
# Editorial Adjudication & Prioritized Revision Roadmap
# ==============================================================================

def adjudicate_panel(
    reports: list[ReviewerReport],
    venue_tier: str = "field_top",
) -> AdjudicationDecision:
    """Synthesize the 5 reviewer reports into an authoritative editorial decision."""
    weights = {
        "eic": 0.20,
        "methodology": 0.25,
        "domain": 0.20,
        "perspective": 0.15,
        "devils_advocate": 0.20,
    }
    composite_score = sum(r.score * weights.get(r.seat_id, 0.2) for r in reports)

    # Count DA Criticals
    da_report = next((r for r in reports if r.seat_id == "devils_advocate"), None)
    da_criticals = [c for c in (da_report.critiques if da_report else []) if c.severity == "CRITICAL"]
    da_critical_count = len(da_criticals)

    # Gather all critiques across reviewers
    all_critiques: list[tuple[str, CritiqueItem]] = []
    for r in reports:
        for c in r.critiques:
            all_critiques.append((r.seat_name, c))

    # Consensus strengths
    consensus_strengths: list[str] = []
    for r in reports:
        consensus_strengths.extend(r.strengths[:2])

    # Consensus weaknesses (categories flagged by >= 2 reviewers)
    cat_counts: dict[str, int] = {}
    for _, c in all_critiques:
        cat_counts[c.category] = cat_counts.get(c.category, 0) + 1
    consensus_weaknesses = [
        f"Multiple reviewers flagged weaknesses in '{cat.upper()}' ({cnt} citations)."
        for cat, cnt in cat_counts.items() if cnt >= 2
    ]

    # Arbitrated disagreements
    arbitrated_disagreements: list[str] = []
    # E.g. If methodology score < 6.0 but domain > 8.0
    meth_rep = next((r for r in reports if r.seat_id == "methodology"), None)
    dom_rep = next((r for r in reports if r.seat_id == "domain"), None)
    if meth_rep and dom_rep and abs(meth_rep.score - dom_rep.score) >= 2.0:
        arbitrated_disagreements.append(
            f"Reviewers diverge on methodological depth vs bibliographic breadth: Domain Reviewer rated {dom_rep.score:.1f} whereas Methodology Reviewer demanded stricter identification ({meth_rep.score:.1f}). Editorial arbitration: Methodological identification rigor must take precedence."
        )

    # Determine Editorial Decision
    # Iron Rule: Any unresolved DA critical or methodology critical prevents unconditional Accept
    any_critical = any(c.severity == "CRITICAL" for _, c in all_critiques)
    
    tier_thresholds = {
        "top": {"accept": 8.8, "minor": 7.5, "major": 5.5},
        "field_top": {"accept": 8.5, "minor": 7.0, "major": 5.0},
        "general": {"accept": 8.0, "minor": 6.5, "major": 4.5},
        "working_paper": {"accept": 7.5, "minor": 6.0, "major": 4.0},
    }
    t = tier_thresholds.get(venue_tier, tier_thresholds["field_top"])

    if composite_score >= t["accept"] and not any_critical:
        decision = "ACCEPT"
    elif composite_score >= t["minor"] and not any_critical:
        decision = "MINOR_REVISION"
    elif composite_score >= t["major"] or any_critical:
        decision = "MAJOR_REVISION"
    else:
        decision = "REJECT_AND_RESUBMIT"

    # Build Prioritized Revision Roadmap
    roadmap: list[RoadmapItem] = []
    for seat_name, c in all_critiques:
        if c.severity == "CRITICAL":
            roadmap.append(RoadmapItem(
                priority="MUST-ADDRESS",
                source_seats=[seat_name],
                issue=c.critique,
                action_required=c.suggested_remedy,
            ))
        elif c.severity == "MAJOR":
            roadmap.append(RoadmapItem(
                priority="RECOMMENDED",
                source_seats=[seat_name],
                issue=c.critique,
                action_required=c.suggested_remedy,
            ))
        else:
            roadmap.append(RoadmapItem(
                priority="POLISH",
                source_seats=[seat_name],
                issue=c.critique,
                action_required=c.suggested_remedy,
            ))

    # Generate Editorial Letter
    ed_letter = _render_editorial_letter(
        decision=decision,
        composite_score=composite_score,
        venue_tier=venue_tier,
        da_critical_count=da_critical_count,
        reports=reports,
        roadmap=roadmap,
    )

    return AdjudicationDecision(
        composite_score=composite_score,
        editorial_decision=decision,
        target_venue_tier=venue_tier,
        reviewer_reports=reports,
        consensus_strengths=consensus_strengths[:4],
        consensus_weaknesses=consensus_weaknesses,
        arbitrated_disagreements=arbitrated_disagreements,
        da_critical_count=da_critical_count,
        revision_roadmap=roadmap,
        editorial_letter=ed_letter,
    )


def _render_editorial_letter(
    decision: str,
    composite_score: float,
    venue_tier: str,
    da_critical_count: int,
    reports: list[ReviewerReport],
    roadmap: list[RoadmapItem],
) -> str:
    """Format formal editorial decision letter."""
    lines: list[str] = [
        f"Dear Author(s),\n",
        f"Thank you for submitting your manuscript for peer-review consideration at a {venue_tier.replace('_', ' ').title()} journal outlet. "
        f"We have now completed a thorough review cycle with our 5-seat referee panel (Journal-Fit, Methodology, Domain Literature, Boundary Conditions, and Devil's Advocate).\n",
        f"**Editorial Decision**: **{decision}** (Composite Review Score: {composite_score:.1f} / 10.0)\n",
    ]

    if da_critical_count > 0:
        lines.append(
            f"> [!IMPORTANT]\n> The Devil's Advocate seat identified {da_critical_count} CRITICAL logical/empirical tension(s). "
            f"Per editorial ethics rules, these concerns must be explicitly resolved in the revision before an unconditional acceptance can be rendered.\n"
        )

    lines.append("### Individual Referee Scores:\n")
    for r in reports:
        lines.append(f"- **{r.seat_name}**: `{r.score:.1f}/10.0` — *{r.summary_verdict}*")

    lines.append("\n### Prioritized Revision Instructions:\n")
    if not roadmap:
        lines.append("The panel finds no major defects; proceed to final copy-editing.")
    else:
        for idx, item in enumerate(roadmap[:6], 1):
            lines.append(f"{idx}. `[{item.priority}]` **{item.issue}**")
            lines.append(f"   *Remedy*: {item.action_required}")

    lines.append("\nWe look forward to receiving your revised manuscript along with a point-by-point Response to Reviewers.\n")
    lines.append("Sincerely,\n*Editorial Review Board & Adjudication Office*")
    return "\n".join(lines)


